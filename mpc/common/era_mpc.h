/* Parameter store: values in each param's own units (as gen_vst.py's params.h declares them). The wrapper sends
 * numbers as text (option lists as their index) and reads them back the same way. */
inline int findParam (const char* key)
{
    for (int i = 0; i < NPARAMS; i++)
        if (! strcmp (PARAMS[i].key, key)) return i;
    return -1;
}

struct ParamStore
{
    float v[NPARAMS];
    unsigned rev;   /* bumped on every change: engines rebuild coefficients when it moves */

    ParamStore() : rev (1) { for (int i = 0; i < NPARAMS; i++) v[i] = PARAMS[i].def; }

    float get (int i) const { return i >= 0 ? v[i] : 0.0f; }
    int opt (int i) const { return i >= 0 ? (int) lroundf (v[i]) : 0; }

    void setIndex (int i, float x)
    {
        const param_t& p = PARAMS[i];
        if (p.nopts) x = clampf (roundf (x), 0.0f, (float) (p.nopts - 1));
        else if (p.max > p.min) x = clampf (x, p.min, p.max);
        if (v[i] != x) { v[i] = x; rev++; }
    }

    /* "state": every parameter as key=value lines (chunk save/restore; order-independent, unknown keys ignored). */
    int saveState (char* buf, int len) const
    {
        int n = 0;
        for (int i = 0; i < NPARAMS && n < len; i++)
            n += snprintf (buf + n, (size_t) (len - n), "%s=%g\n", PARAMS[i].key, (double) v[i]);
        return n < len ? n : len - 1;
    }
    void loadState (const char* s)
    {
        char key[64];
        while (*s)
        {
            const char* eq = strchr (s, '=');
            const char* nl = strchr (s, '\n');
            if (! eq || (nl && nl < eq)) { if (! nl) break; s = nl + 1; continue; }
            int kl = (int) (eq - s); if (kl > 63) kl = 63;
            memcpy (key, s, (size_t) kl); key[kl] = 0;
            const int i = findParam (key);
            if (i >= 0 && strncmp (PARAMS[i].key, "__", 2)) setIndex (i, (float) atof (eq + 1));
            if (! nl) break;
            s = nl + 1;
        }
    }

    /* Common set/get for engine.h: returns 1 if the key was a stored parameter. */
    bool set (const char* key, const char* val)
    {
        if (! strcmp (key, "state")) { loadState (val); return true; }
        const int i = findParam (key);
        if (i < 0) return false;
        setIndex (i, (float) atof (val));
        return true;
    }
    int get (const char* key, char* buf, int len) const
    {
        if (! strcmp (key, "state")) return saveState (buf, len);
        const int i = findParam (key);
        if (i < 0) return 0;
        if (PARAMS[i].nopts) return snprintf (buf, (size_t) len, "%d", (int) lroundf (v[i]));
        return snprintf (buf, (size_t) len, "%g", (double) v[i]);
    }
};

/* Display helpers (value text MPC shows under a knob; "<key>_display" for params with "dynamic_display"). */
inline int fmtHz (char* b, int n, float hz)
{
    if (hz >= 10000.0f) return snprintf (b, (size_t) n, "%.1f kHz", hz / 1000.0f);
    if (hz >= 1000.0f)  return snprintf (b, (size_t) n, "%.2f kHz", hz / 1000.0f);
    if (hz < 100.0f)    return snprintf (b, (size_t) n, "%.1f Hz", hz);
    return snprintf (b, (size_t) n, "%.0f Hz", hz);
}
inline int fmtMs (char* b, int n, float ms)
{
    if (ms >= 1000.0f) return snprintf (b, (size_t) n, "%.2f s", ms / 1000.0f);
    if (ms < 1.0f)     return snprintf (b, (size_t) n, "%.2f ms", ms);
    if (ms < 10.0f)    return snprintf (b, (size_t) n, "%.1f ms", ms);
    return snprintf (b, (size_t) n, "%.0f ms", ms);
}
inline int fmtDb (char* b, int n, float db) { return snprintf (b, (size_t) n, db > 0.05f ? "+%.1f dB" : "%.1f dB", db); }

/* True if `key` is "<param>_display" for one of the given params; puts the param's index in *idx. */
inline bool isDisplayKey (const char* key, int* idx)
{
    const size_t kl = strlen (key);
    if (kl < 9 || strcmp (key + kl - 8, "_display")) return false;
    char base[64];
    if (kl - 8 >= sizeof base) return false;
    memcpy (base, key, kl - 8); base[kl - 8] = 0;
    *idx = findParam (base);
    return *idx >= 0;
}

