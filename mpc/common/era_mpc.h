/* Cytomic trapezoidal SVF (same as the desktop Era-Q): stable under modulation. */
enum SvfType { SvfBell, SvfLowShelf, SvfHighShelf, SvfLowPass, SvfHighPass, SvfNotch };

struct SvfCoeffs
{
    float a1, a2, a3, m0, m1, m2;
    SvfCoeffs() : a1 (1), a2 (0), a3 (0), m0 (1), m1 (0), m2 (0) {}

    static SvfCoeffs make (SvfType type, double freq, double q, double gainDb, double sr)
    {
        SvfCoeffs c;
        if (freq < 5.0) freq = 5.0;
        if (freq > sr * 0.49) freq = sr * 0.49;
        if (q < 0.025) q = 0.025;
        const double A = pow (10.0, gainDb / 40.0);
        const double base = tan (kPi * freq / sr);
        double g = base, k = 1.0 / q, m0 = 1, m1 = 0, m2 = 0;
        switch (type)
        {
            case SvfLowPass:  m0 = 0; m1 = 0;  m2 = 1; break;
            case SvfHighPass: m0 = 1; m1 = -k; m2 = -1; break;
            case SvfNotch:    m0 = 1; m1 = -k; m2 = 0; break;
            case SvfBell:     k = 1.0 / (q * A); m0 = 1; m1 = k * (A * A - 1.0); m2 = 0; break;
            case SvfLowShelf: g = base / sqrt (A); m0 = 1; m1 = k * (A - 1.0); m2 = A * A - 1.0; break;
            case SvfHighShelf:g = base * sqrt (A); m0 = A * A; m1 = k * (1.0 - A) * A; m2 = 1.0 - A * A; break;
        }
        const double a1 = 1.0 / (1.0 + g * (g + k));
        c.a1 = (float) a1; c.a2 = (float) (g * a1); c.a3 = (float) (g * g * a1);
        c.m0 = (float) m0; c.m1 = (float) m1; c.m2 = (float) m2;
        return c;
    }
};

struct SvfState
{
    float ic1, ic2;
    SvfState() : ic1 (0), ic2 (0) {}
    void reset() { ic1 = ic2 = 0; }
    inline float process (float v0, const SvfCoeffs& c)
    {
        const float v3 = v0 - ic2;
        const float v1 = c.a1 * ic1 + c.a2 * v3;
        const float v2 = ic2 + c.a2 * ic1 + c.a3 * v3;
        ic1 = 2.0f * v1 - ic1;
        ic2 = 2.0f * v2 - ic2;
        return c.m0 * v0 + c.m1 * v1 + c.m2 * v2;
    }
};

/* RBJ biquad, Direct Form I (same formulas as the desktop DspUtils.h). */
struct Biquad
{
    float b0, b1, b2, a1, a2, x1, x2, y1, y2;
    Biquad() : b0 (1), b1 (0), b2 (0), a1 (0), a2 (0), x1 (0), x2 (0), y1 (0), y2 (0) {}
    void reset() { x1 = x2 = y1 = y2 = 0; }
    inline float process (float x)
    {
        const float y = b0 * x + b1 * x1 + b2 * x2 - a1 * y1 - a2 * y2;
        x2 = x1; x1 = x; y2 = y1; y1 = y;
        return y;
    }
    void set (double B0, double B1, double B2, double A0, double A1, double A2)
    {
        b0 = (float) (B0 / A0); b1 = (float) (B1 / A0); b2 = (float) (B2 / A0);
        a1 = (float) (A1 / A0); a2 = (float) (A2 / A0);
    }
    static double w0 (double f, double sr) { if (f < 5) f = 5; if (f > sr * 0.49) f = sr * 0.49; return 2.0 * kPi * f / sr; }
    void highPass (double f, double q, double sr)
    {
        const double w = w0 (f, sr), cs = cos (w), al = sin (w) / (2 * q);
        set ((1 + cs) / 2, -(1 + cs), (1 + cs) / 2, 1 + al, -2 * cs, 1 - al);
    }
    void lowPass (double f, double q, double sr)
    {
        const double w = w0 (f, sr), cs = cos (w), al = sin (w) / (2 * q);
        set ((1 - cs) / 2, 1 - cs, (1 - cs) / 2, 1 + al, -2 * cs, 1 - al);
    }
    void lowShelf (double f, double q, double db, double sr)
    {
        const double A = pow (10.0, db / 40.0), w = w0 (f, sr), cs = cos (w), al = sin (w) / (2 * q), sa = 2 * sqrt (A) * al;
        set (A * ((A + 1) - (A - 1) * cs + sa), 2 * A * ((A - 1) - (A + 1) * cs), A * ((A + 1) - (A - 1) * cs - sa),
             (A + 1) + (A - 1) * cs + sa, -2 * ((A - 1) + (A + 1) * cs), (A + 1) + (A - 1) * cs - sa);
    }
    void highShelf (double f, double q, double db, double sr)
    {
        const double A = pow (10.0, db / 40.0), w = w0 (f, sr), cs = cos (w), al = sin (w) / (2 * q), sa = 2 * sqrt (A) * al;
        set (A * ((A + 1) + (A - 1) * cs + sa), -2 * A * ((A - 1) + (A + 1) * cs), A * ((A + 1) + (A - 1) * cs - sa),
             (A + 1) - (A - 1) * cs + sa, 2 * ((A - 1) - (A + 1) * cs), (A + 1) - (A - 1) * cs - sa);
    }
    void peak (double f, double q, double db, double sr)
    {
        const double A = pow (10.0, db / 40.0), w = w0 (f, sr), cs = cos (w), al = sin (w) / (2 * q);
        set (1 + al * A, -2 * cs, 1 - al * A, 1 + al / A, -2 * cs, 1 - al / A);
    }
};

struct DcBlocker
{
    float x1, y1, r;
    DcBlocker() : x1 (0), y1 (0), r ((float) exp (-2.0 * kPi * 8.0 / kSampleRate)) {}
    void reset() { x1 = y1 = 0; }
    inline float process (float x) { const float y = x - x1 + r * y1; x1 = x; y1 = y; return y; }
};

/* Linear ramp toward a target over a fixed time: zipper-free knob moves. */
struct Ramp
{
    float cur, target, step; int left, len;
    Ramp() : cur (0), target (0), step (0), left (0), len (2205) {}
    void setTime (float seconds) { len = (int) (seconds * kSampleRate); if (len < 1) len = 1; }
    void snap (float v) { cur = target = v; left = 0; }
    void set (float v)
    {
        if (v == target) return;
        target = v; left = len; step = (target - cur) / (float) len;
    }
    inline float next() { if (left > 0) { cur += step; if (--left == 0) cur = target; } return cur; }
    bool moving() const { return left > 0; }
};

/* xorshift32: per-instance noise for the vinyl dust. */
struct Rng
{
    uint32_t s;
    Rng() : s (0x8cee1990u) {}
    inline uint32_t next() { s ^= s << 13; s ^= s >> 17; s ^= s << 5; return s; }
    inline float uni() { return (float) (next() >> 8) * (1.0f / 16777216.0f); }   /* 0..1 */
};

