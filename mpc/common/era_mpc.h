/* Glue: an engine class with process()/display() becomes an mpc_engine_t. */
template <class E>
struct EngineGlue
{
    static void* create (const char*) { return new E(); }
    static void destroy (void* p) { delete (E*) p; }
    static void midi (void*, const uint8_t*, int) {}
    static void setParam (void* p, const char* k, const char* v) { ((E*) p)->params.set (k, v); }
    static int getParam (void* p, const char* k, char* b, int n)
    {
        E* e = (E*) p;
        int idx;
        if (isDisplayKey (k, &idx)) return e->display (idx, b, n);
        return e->params.get (k, b, n);
    }
    static void render (void*, int16_t* out, int frames) { memset (out, 0, sizeof (int16_t) * 2 * (size_t) frames); }
    static void process (void* p, const int16_t* in, int16_t* out, int frames) { ((E*) p)->process (in, out, frames); }
    static const mpc_engine_t* get()
    {
        static const mpc_engine_t api = { create, destroy, midi, setParam, getParam, render, process, 0 };
        return &api;
    }
};
