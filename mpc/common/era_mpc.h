/* 8cee Golden Era Bundle -- shared, JUCE-free DSP and engine plumbing for the MPC OS ports.
 *
 * Each port implements mpc_engine() (mpc-vst-plugins wrapper/engine.h) as an effect: interleaved int16 stereo,
 * 44.1 kHz, 128-frame blocks. The algorithms follow the desktop plug-ins in ../../plugins, trimmed for the MPC's
 * ARM CPU (coefficients per sub-block, a cheap 2x oversampler, no analyzers).
 *
 * Kept to C++11 and plain arrays: build_port.sh compiles with -std=gnu++11 for armhf (glibc 2.31). */
